// Makes ./app fully offline: downloads the Google Fonts and three.js that the web app loads
// from the internet, and points the app at the local copies. Needs internet once, at build time.
const fs = require('fs'), path = require('path'), https = require('https'), crypto = require('crypto');
const APP = path.join(__dirname, '..', 'app');
const FAKE = !!process.env.VENDOR_FAKE; // test mode, no network
const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36';

function get(url) {
  if (FAKE) return Promise.resolve(Buffer.from(url.includes('googleapis.com/css2')
    ? '@font-face{font-family:Fake;src:url(https://fonts.gstatic.com/s/fake/a.woff2) format("woff2")}'
    : 'FAKE'));
  return new Promise((resolve, reject) => {
    https.get(url, { headers: { 'User-Agent': UA } }, res => {
      if (res.statusCode >= 300 && res.statusCode < 400 && res.headers.location) return resolve(get(new URL(res.headers.location, url).href));
      if (res.statusCode !== 200) return reject(new Error(res.statusCode + ' ' + url));
      const chunks = []; res.on('data', c => chunks.push(c)); res.on('end', () => resolve(Buffer.concat(chunks)));
    }).on('error', reject);
  });
}

(async () => {
  /* 1. Google Fonts -> assets/fonts + assets/css/00-fonts.css */
  const indexPath = path.join(APP, 'index.html');
  let html = fs.readFileSync(indexPath, 'utf8');
  const linkRe = /<link[^>]+href="(https:\/\/fonts\.googleapis\.com\/[^"]+)"[^>]*>\s*/g;
  const urls = [...html.matchAll(linkRe)].map(m => m[1].replace(/&amp;/g, '&'));
  if (!urls.length) throw new Error('no Google Fonts links found in index.html');
  fs.mkdirSync(path.join(APP, 'assets', 'fonts'), { recursive: true });
  let css = '/* Local copy of the Google Fonts used by Pines (generated by scripts/vendor.js) */\n';
  const done = new Map();
  for (const u of urls) {
    let c = (await get(u)).toString('utf8');
    for (const f of new Set([...c.matchAll(/url\((https:\/\/fonts\.gstatic\.com\/[^)]+)\)/g)].map(m => m[1]))) {
      if (!done.has(f)) {
        const name = crypto.createHash('sha1').update(f).digest('hex').slice(0, 16) + '.woff2';
        fs.writeFileSync(path.join(APP, 'assets', 'fonts', name), await get(f));
        done.set(f, name);
      }
      c = c.split(f).join('../fonts/' + done.get(f));
    }
    css += c + '\n';
  }
  fs.writeFileSync(path.join(APP, 'assets', 'css', '00-fonts.css'), css);
  let first = true;
  html = html.replace(linkRe, () => { if (first) { first = false; return '<link rel="stylesheet" href="assets/css/00-fonts.css">\n'; } return ''; });
  fs.writeFileSync(indexPath, html);
  console.log('vendor: fonts ->', done.size, 'files');

  /* 2. three.js (Visualize tab) */
  const THREE = 'https://cdnjs.cloudflare.com/ajax/libs/three.js/r128/three.min.js';
  const vizPath = path.join(APP, 'js', 'views', 'visualize.js');
  let viz = fs.readFileSync(vizPath, 'utf8');
  if (!viz.includes(THREE)) throw new Error('three.js URL not found in visualize.js');
  fs.mkdirSync(path.join(APP, 'vendor'), { recursive: true });
  fs.writeFileSync(path.join(APP, 'vendor', 'three.min.js'), await get(THREE));
  fs.writeFileSync(vizPath, viz.split(THREE).join('vendor/three.min.js'));
  console.log('vendor: three.js r128 saved');

  /* 3. safety check */
  const left = [];
  (function walk(d) { for (const e of fs.readdirSync(d, { withFileTypes: true })) { const p = path.join(d, e.name);
    if (e.isDirectory()) walk(p); else if (/\.(html|css|js)$/.test(e.name)) { const t = fs.readFileSync(p, 'utf8'); if (/fonts\.googleapis\.com|cdnjs\.cloudflare\.com/.test(t)) left.push(p); } } })(APP);
  if (left.length) throw new Error('still online-only references in: ' + left.join(', '));
  console.log('vendor: OK, app is offline-ready');
})().catch(e => { console.error('vendor FAILED:', e.message); process.exit(1); });
